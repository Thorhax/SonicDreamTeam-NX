#!/usr/bin/env python3
"""Write source/sdt_vk_table.c: every public vk* entry point of the Mesa SDK's
libvulkan.a by name, for the dlsym("vk...") the engine does on "libvulkan.so".

usage: gen_vk_table.py <nm-output-or-symbol-list> > source/sdt_vk_table.c
  (aarch64-none-elf-nm -g --defined-only libvulkan.a | awk 'NF==3{print $3}' | sort -u)
"""
import sys, re
names = sorted({l.split()[-1] for l in open(sys.argv[1]) if re.fullmatch(r'vk[A-Z][A-Za-z0-9]+', l.split()[-1] if l.split() else '')})
print('/* GENERATED by tools/gen_vk_table.py from the Mesa SDK -- do not edit. */')
print('#include <stddef.h>\n#include "sdt_port.h"\n')
for n in names: print(f'extern void {n}(void);')
print('\nconst SdtVkEntry sdt_vk_table[] = {')
for n in names: print(f'  {{ "{n}", (void *){n} }},')
print('};\nconst size_t sdt_vk_table_n = sizeof sdt_vk_table / sizeof sdt_vk_table[0];')
